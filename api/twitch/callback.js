import { consumeOAuthState, completeTwitchOAuth } from "../../lib/twitch.js";

function page(title, message, status = 200) {
  const safeTitle = String(title).replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]));
  const safeMessage = String(message).replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;" }[c]));
  const html = `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width,initial-scale=1">
  <title>${safeTitle} · BeuraVerse</title>
  <style>
    body{margin:0;min-height:100vh;display:grid;place-items:center;background:#090611;color:#f5f1ff;font:16px/1.6 system-ui,sans-serif}
    main{width:min(560px,calc(100% - 40px));padding:32px;border:1px solid #51328a;border-radius:20px;background:#171020;box-shadow:0 20px 80px #0008}
    h1{margin:0 0 12px;color:#c7a5ff;font-size:28px}p{margin:0;color:#d8cee8}
    small{display:block;margin-top:24px;color:#9c8eaf}
  </style>
</head>
<body><main><h1>${safeTitle}</h1><p>${safeMessage}</p><small>BeuraVerse · Twitch connection</small></main></body></html>`;
  return new Response(html, {
    status,
    headers: {
      "Content-Type": "text/html; charset=utf-8",
      "Cache-Control": "no-store, private",
      "X-Content-Type-Options": "nosniff",
      "Referrer-Policy": "no-referrer"
    }
  });
}

export default async function handler(request) {
  if (request.method !== "GET") {
    return page("Method not allowed", "Use the Twitch authorization link generated by BeuraVerse.", 405);
  }

  const url = new URL(request.url);
  const state = url.searchParams.get("state");
  if (!state || !(await consumeOAuthState(state))) {
    return page("Authorization link expired", "This one-time link is invalid or has expired. Return to ChatGPT and run start_twitch_authorization again.", 400);
  }

  const oauthError = url.searchParams.get("error");
  if (oauthError) {
    return page("Authorization not completed", "Twitch authorization was declined or cancelled. No account was connected.", 400);
  }

  const code = url.searchParams.get("code");
  if (!code) {
    return page("Authorization incomplete", "Twitch did not return an authorization code. Return to ChatGPT and try again.", 400);
  }

  try {
    const session = await completeTwitchOAuth(code);
    const displayName = session.profile?.displayName || session.profile?.login || "your Twitch account";
    return page("Twitch connected", `BeuraVerse is now connected to ${displayName}. You can close this tab and return to ChatGPT to view your channel information.`);
  } catch (error) {
    console.error("BeuraVerse Twitch OAuth callback failed:", error?.message || "Unknown error");
    const message = process.env.TWITCH_CLIENT_SECRET
      ? "The authorization could not be completed. Return to ChatGPT and retry the connection."
      : "The server is missing TWITCH_CLIENT_SECRET. Add it to the Vercel project environment and redeploy, then retry.";
    return page("Connection failed", message, 500);
  }
}
